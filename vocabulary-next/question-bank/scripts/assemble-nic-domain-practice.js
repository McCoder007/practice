#!/usr/bin/env node
// Builds the learner-facing NIC Domain Practice files from the reviewed sets:
//   nic-domain-practice/questions.json  (all shipped questions, in set order)
//   data/nic-domain-practice/index.generated.ts (topics and sets with counts, for menus)
// Only sets with status "reviewed" ship. `--check` fails if the files are stale.

const fs = require("node:fs")
const path = require("node:path")

const bankDir = path.resolve(__dirname, "../nic-domain-practice")
const setsDir = path.join(bankDir, "sets")
const questionsPath = path.join(bankDir, "questions.json")
const indexPath = path.resolve(__dirname, "../../data/nic-domain-practice/index.generated.ts")
const checkOnly = process.argv.includes("--check")

const setFiles = fs.readdirSync(setsDir).filter((f) => f.endsWith(".json")).sort()
const sets = setFiles.map((file) => JSON.parse(fs.readFileSync(path.join(setsDir, file), "utf8")))
const shipped = sets.filter((set) => set.status === "reviewed")
const held = sets.filter((set) => set.status !== "reviewed")

const domains = new Map()
const questions = []
for (const set of shipped) {
  const d = set.domain
  if (!domains.has(d.id)) {
    domains.set(d.id, { id: d.id, order: d.order, title: d.title, examWeightPercent: d.examWeightPercent, sets: [] })
  }
  const domain = domains.get(d.id)
  const offset = domain.sets.reduce((sum, s) => sum + s.count, 0)
  domain.sets.push({ setId: set.setId, title: set.title, offset, count: set.questions.length })
  for (const q of set.questions) {
    questions.push({
      id: q.id,
      setId: set.setId,
      domainId: d.id,
      question: q.question,
      choices: q.choices,
      correctChoice: q.correctChoice,
      explanation: q.explanation,
      lockPoint: q.lockPoint,
      hookType: q.hookType,
      status: "approved",
    })
  }
}

const domainList = [...domains.values()].sort((a, b) => a.order - b.order)
for (const domain of domainList) domain.questionCount = domain.sets.reduce((sum, s) => sum + s.count, 0)

const sourceTitle = "NIC Domain Practice (written from Milady Standard Nail Technology 8th ed. + Foundations)"
const questionsFile = {
  schemaVersion: "1.0.0",
  language: { source: "en", translation: "zh-Hans" },
  sourceTitle,
  statistics: { total: questions.length, sets: shipped.length },
  questions,
}
const indexFile = {
  schemaVersion: "1.0.0",
  sourceTitle,
  totalQuestions: questions.length,
  domains: domainList,
}

const questionsText = `${JSON.stringify(questionsFile, null, 2)}\n`
const indexText = `// Generated by question-bank/scripts/assemble-nic-domain-practice.js. Do not edit.\n\nexport const EXAM_TOPIC_INDEX = ${JSON.stringify(indexFile, null, 2)} as const\n`

if (checkOnly) {
  const stale = [
    [questionsPath, questionsText],
    [indexPath, indexText],
  ].filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text)
  if (stale.length) {
    console.error(`NIC Domain Practice files are out of date: ${stale.map(([f]) => path.basename(f)).join(", ")}`)
    console.error("Run: npm run assemble:nic-domain-practice")
    process.exit(1)
  }
  console.log(`NIC Domain Practice assembled files are current (${questions.length} questions).`)
  process.exit(0)
}

fs.writeFileSync(questionsPath, questionsText)
fs.writeFileSync(indexPath, indexText)
console.log(`Wrote ${questions.length} questions from ${shipped.length} reviewed set(s).`)
if (held.length) console.log(`Held back (not reviewed): ${held.map((s) => `${s.setId} (${s.status})`).join(", ")}`)
